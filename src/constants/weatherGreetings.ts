let cachedWeatherCode: number | null = null;

export function setCachedWeatherCode(code: number): void {
  cachedWeatherCode = code;
}

export function getCachedWeatherCode(): number | null {
  return cachedWeatherCode;
}

/**
 * 날씨 코드와 사용자 이름을 기반으로 맞춤형 인삿말을 생성합니다.
 */
export function getWeatherGreeting(
  weatherCode: number | null | undefined = cachedWeatherCode,
  userName: string = "학생",
  date = new Date()
): string {
  const timeSlot = getTimeSlot(date);
  let template = "";

  if (weatherCode && WEATHER_GREETINGS[weatherCode]) {
    template = WEATHER_GREETINGS[weatherCode][timeSlot];
  }

  if (!template) {
    template = DEFAULT_TIME_GREETINGS[timeSlot];
  }

  const nameToUse = userName.trim() || "학생";
  return template.replace(/사용자님/g, `${nameToUse}님`).replace(/사용자/g, nameToUse);
}
