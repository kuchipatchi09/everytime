export type TimeSlot = "새벽" | "아침" | "낮" | "저녁" | "밤";

export function getTimeSlot(date = new Date()): TimeSlot {
  const h = date.getHours();
  if (h >= 0 && h < 6) return "새벽";
  if (h >= 6 && h < 11) return "아침";
  if (h >= 11 && h < 17) return "낮";
  if (h >= 17 && h < 21) return "저녁";
  return "밤";
}

