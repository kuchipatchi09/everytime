import { RoutineItem } from "../types/timetable";

export function getRoutine(day: number): RoutineItem[] {
  const morning: RoutineItem[] = [
    ["00:00", "08:30", "취침 및 등교 준비"],
    ["08:30", "08:40", "아침 조회"],
    ["08:40", "09:30", "1교시"],
    ["09:30", "09:40", "쉬는 시간"],
    ["09:40", "10:30", "2교시"],
    ["10:30", "10:40", "쉬는 시간"],
    ["10:40", "11:30", "3교시"],
    ["11:30", "11:40", "쉬는 시간"],
    ["11:40", "12:30", "4교시"],
  ];

  if (day === 0) {
    return [
      ["00:00", "20:00", "귀사 준비"],
      ["20:00", "21:30", "야간 자율학습"],
      ["21:30", "22:20", "개인 정비 시간"],
      ["22:20", "24:10", "기숙사 야자"],
      ["24:10", "24:30", "개인정비 및 점호 준비"],
      ["24:30", "24:59", "취침"],
    ];
  }

  if (day === 6) {
    return [["00:00", "24:59", "등록된 일과 없음"]];
  }

  const afternoon: RoutineItem[] =
    day === 3
      ? [
          ["12:30", "13:50", "점심시간"],
          ["13:50", "14:40", "5교시"],
          ["14:40", "15:30", "6교시"],
          ["15:30", "16:20", "7교시"],
        ]
      : [
          ["12:30", "13:30", "점심시간"],
          ["13:30", "14:20", "5교시"],
          ["14:20", "14:30", "쉬는 시간"],
          ["14:30", "15:20", "6교시"],
          ["15:20", "15:30", "쉬는 시간"],
          ["15:30", "16:20", "7교시"],
        ];

  if (day === 5) {
    return [...morning, ...afternoon, ["16:20", "24:59", "종례 후 귀가"]];
  }

  return [
    ...morning,
    ...afternoon,
    ["16:20", "16:30", "청소 시간"],
    ["16:30", "17:50", "8교시 (방과후)"],
    ["17:50", "19:00", "저녁시간"],
    ["19:00", "20:20", "야자 1교시"],
    ["20:20", "20:30", "쉬는 시간"],
    ["20:30", "21:30", "야자 2교시"],
    ["21:30", "22:20", "개인 정비 시간"],
    ["22:20", "24:10", "기숙사 야자"],
    ["24:10", "24:30", "개인정비 및 점호 준비"],
    ["24:30", "24:59", "취침"],
  ];
}
